def test_clean_content_passes_through(monkeypatch):
    """The filter must not be so eager that ordinary traffic trips it."""
    provider = CapturingProvider()
    client = create_policy_client(monkeypatch, provider)

    response = post_chat(
        client,
        POLICY_HEADERS,
        [{"role": "user", "content": "What is the weather in Lisbon?"}],
    )

    assert response.status_code == 200
    assert len(provider.requests) == 1
