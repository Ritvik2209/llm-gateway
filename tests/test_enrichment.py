def test_a_disclaimer_is_appended_to_the_response(monkeypatch):
    provider = CapturingProvider()
    client = create_policy_client(monkeypatch, provider)

    response = post_chat(client, POLICY_HEADERS, [{"role": "user", "content": "Hello"}])

    assert response.status_code == 200
    assert response.json()["content"] == f"ok\n\n{DISCLAIMER}"


def test_blocked_content_never_reaches_a_provider(monkeypatch):
    """The point of blocking rather than instructing: the content does not leave the building."""
    provider = CapturingProvider()
    client = create_policy_client(monkeypatch, provider)

    response = post_chat(
        client,
        POLICY_HEADERS,
        [{"role": "user", "content": "my SSN is on file"}],
    )

    assert response.status_code == 400
    assert "content policy" in response.json()["detail"].lower()
    assert provider.requests == []


